RBI_AML_GUIDELINES = """
RBI MASTER DIRECTION ON KNOW YOUR CUSTOMER (KYC) AND ANTI-MONEY LAUNDERING (AML)

CHAPTER 1: PRELIMINARY
1.1 These directions shall be applicable to all Scheduled Commercial Banks, Regional Rural Banks, Local Area Banks, Primary (Urban) Co-operative Banks, and all Non-Banking Financial Companies.

1.2 The objective of KYC/AML/CFT guidelines is to prevent banks and financial institutions from being used, intentionally or unintentionally, by criminal elements for money laundering or terrorist financing activities.

CHAPTER 2: CUSTOMER IDENTIFICATION PROCEDURE
2.1 No bank shall open an account or conduct a transaction with an anonymous or fictitious customer.

2.2 Banks must verify the identity of every customer through reliable, independent source documents, data or information.

2.3 For high-risk customers, including politically exposed persons (PEPs), enhanced due diligence (EDD) is mandatory.

2.4 Banks must maintain updated customer information through periodic KYC updation at intervals prescribed based on risk categorization.

CHAPTER 3: RISK CATEGORIZATION
3.1 Customers shall be categorized as low, medium, or high risk based on their profile, nature of business, transaction patterns, and geographic considerations.

3.2 Low-risk customers: Salaried individuals, government departments, publicly listed companies with good track record.

3.3 Medium-risk customers: Private companies, partnership firms, trusts, and individuals with moderate transaction volumes.

3.4 High-risk customers: Non-resident accounts, politically exposed persons, cash-intensive businesses, and customers from high-risk jurisdictions.

CHAPTER 4: TRANSACTION MONITORING
4.1 Banks shall put in place a robust transaction monitoring system to detect suspicious transactions.

4.2 Cash transactions exceeding Rs. 10 lakh (or equivalent in foreign currency) must be reported to the Financial Intelligence Unit (FIU-IND).

4.3 All suspicious transactions, regardless of amount, must be reported to FIU-IND within 7 days of detection.

4.4 Structuring indicators include: multiple cash transactions just below reporting threshold, transactions at multiple branches, and use of multiple accounts to avoid reporting.

CHAPTER 5: CURRENCY TRANSACTION REPORT (CTR)
5.1 Every bank must file CTR for all cash transactions exceeding Rs. 10 lakh within the prescribed time.

5.2 CTR must include: customer details, transaction details, account information, and branch details.

5.3 Banks must aggregate all cash transactions of a customer during a month to determine reporting obligation.

CHAPTER 6: SUSPICIOUS TRANSACTION REPORT (STR)
6.1 STR must be filed for any transaction that gives rise to a reasonable ground of suspicion.

6.2 STR confidentiality is absolute - no tipping off is permitted.

6.3 STR must contain: detailed narration of suspicion, transaction details, customer identification, and relevant supporting documents.

CHAPTER 7: RECORD KEEPING
7.1 All records of transactions must be preserved for at least 5 years after the business relationship ends.

7.2 Banks must maintain all necessary records for investigation of criminal activity.

7.3 Failure to maintain records may result in penalty under PMLA, 2002.

CHAPTER 8: REPORTING TO FIU-IND
8.1 Reports must be filed in the prescribed format through the FINnet portal.

8.2 Non-compliance may result in monetary penalties, suspension of license, or criminal prosecution.

SCHEDULE I: INDICATORS OF MONEY LAUNDERING
- Unusual transaction patterns inconsistent with customer profile
- Rapid movement of funds across multiple accounts
- Transactions designed to avoid reporting thresholds
- Use of multiple accounts or third parties to obscure beneficial ownership
- Geographic anomalies in transaction origination
- Sudden increase in transaction volume or frequency
- Transactions involving high-risk jurisdictions
- Use of layered corporate structures without economic rationale

SCHEDULE II: ENHANCED DUE DILIGENCE MEASURES
- Obtain additional customer identification documents
- Verify source of funds and source of wealth
- Conduct more frequent transaction monitoring
- Subject transactions to additional scrutiny
- Require senior management approval for high-risk relationships
"""

FATF_RECOMMENDATIONS = """
FATF 40 RECOMMENDATIONS — INTERNATIONAL STANDARDS ON COMBATING MONEY LAUNDERING

RECOMMENDATION 1: ASSESSING RISKS AND APPLYING A RISK-BASED APPROACH
Countries should identify, assess, and understand the money laundering and terrorist financing risks for the country. Based on that assessment, they should apply a risk-based approach to ensure measures to prevent or mitigate ML/TF are commensurate with the risks identified.

RECOMMENDATION 2: NATIONAL COOPERATION AND COORDINATION
Countries should have a national AML/CFT policy and designate an authority to coordinate implementation. This includes establishing a Financial Intelligence Unit (FIU).

RECOMMENDATION 3: MONEY LAUNDERING OFFENCE
Countries should criminalize money laundering based on the Vienna Convention and the Palermo Convention.

RECOMMENDATION 4: CONFISCATION AND PROVISIONAL MEASURES
Countries should adopt measures to confiscate proceeds of crime, property of corresponding value, and instrumentalities used in or destined for use in ML/TF offences.

RECOMMENDATION 5: CUSTOMER DUE DILIGENCE (CDD)
Financial institutions should not keep anonymous accounts or accounts in obviously fictitious names. CDD measures include: identifying the customer and verifying identity using reliable documents, identifying beneficial ownership, understanding the purpose of the business relationship, and conducting ongoing due diligence.

RECOMMENDATION 6: POLITICALLY EXPOSED PERSONS (PEPS)
Enhanced due diligence is required for foreign PEPs. Measures include: having appropriate risk management systems, determining source of wealth, and conducting enhanced ongoing monitoring.

RECOMMENDATION 7: CROSS-BORDER CORRESPONDENT BANKING
Enhanced due diligence is required for cross-border correspondent banking relationships. This includes: gathering sufficient information about the respondent institution, assessing its AML/CFT controls, and obtaining senior management approval.

RECOMMENDATION 8: NEW TECHNOLOGIES
Countries should ensure that financial institutions identify and assess ML/TF risks that may arise in relation to the development of new products, new business practices, or the use of new or developing technologies.

RECOMMENDATION 9: THIRD-PARTY RELIANCE ON CDD
Countries may permit financial institutions to rely on third parties for CDD, but the ultimate responsibility remains with the financial institution.

RECOMMENDATION 10: RECORD KEEPING
Financial institutions should maintain all necessary records on transactions and customer identification for at least five years after the business relationship ends or the transaction is completed.

RECOMMENDATION 11: UNUSUAL TRANSACTIONS
Financial institutions should pay special attention to all complex, unusual large transactions, and all unusual patterns of transactions that have no apparent economic or visible lawful purpose.

RECOMMENDATION 12: REPORTING OF SUSPICIOUS TRANSACTIONS
If a financial institution suspects or has reasonable grounds to suspect that funds are the proceeds of criminal activity, it should report promptly to the FIU.

RECOMMENDATION 13: TIPPING OFF
Financial institutions, their directors, officers and employees should be prohibited from disclosing the fact that a suspicious transaction report or related information is being reported to the FIU.

RECOMMENDATION 14: PROTECTION OF REPORTING INDIVIDUALS
Countries should protect employees who report suspicious transactions from legal liability for breach of confidentiality restrictions.

RECOMMENDATION 15: INTERNAL CONTROLS AND FOREIGN BRANCHES
Financial institutions should develop internal controls, compliance management, and audit functions to combat ML/TF. This includes group-level AML/CFT programmes applicable to all branches and subsidiaries.

RECOMMENDATION 16: SHELL BANKS
Countries should ensure that financial institutions do not enter into or continue correspondent banking relationships with shell banks.

RECOMMENDATION 17: RELIANCE ON INTRODUCED BUSINESS
Countries may permit financial institutions to rely on another financial institution for CDD under certain conditions.

RECOMMENDATION 18: HIGHER-RISK COUNTRIES
Enhanced due diligence should be applied to business relationships and transactions involving countries identified as having inadequate AML/CFT systems.

RECOMMENDATION 19: REPORTING OF CROSS-BORDER WIRE TRANSFERS
Countries should ensure that financial institutions include accurate originator information and required beneficiary information on wire transfers.

RECOMMENDATION 20: POWERS OF LAW ENFORCEMENT
Countries should ensure that competent authorities have powers to compel production of financial institution records, conduct searches, and take witness statements.

RECOMMENDATION 21: NON-FINANCIAL BUSINESSES
Designated non-financial businesses and professions (DNFBPs) are also subject to AML/CFT requirements, including casinos, real estate agents, dealers in precious metals/stones, lawyers, notaries, and accountants.

RECOMMENDATION 22: SUPERVISION
Countries should ensure that financial institutions are subject to adequate regulation and supervision for AML/CFT purposes.

RECOMMENDATION 23 - 40: INTERNATIONAL COOPERATION
Countries should provide mutual legal assistance, extradition, and other forms of international cooperation for ML/TF investigations and proceedings. This includes sharing of information between FIUs, facilitating cross-border investigations, and ensuring effective implementation of UN sanctions.

GLOSSARY — KEY TERMS
- Beneficial Owner: The natural person(s) who ultimately owns or controls a customer and/or the natural person on whose behalf a transaction is being conducted.
- Financial Institution: Any entity that conducts financial activities as a business, including banks, money service businesses, and securities firms.
- Designated Categories of Offences: Twenty categories of serious crime that serve as predicate offences for money laundering.
- Suspicious Transaction: A transaction that gives rise to a reasonable ground of suspicion that it may involve ML/TF proceeds.
"""

FINCEN_STRUCTURING_RULES = """
FinCEN CURRENCY TRANSACTION REPORT (CTR) AND STRUCTURING GUIDANCE

SECTION 1: LEGAL FRAMEWORK
Under the Bank Secrecy Act (BSA), 31 USC 5311-5336, and implementing regulations at 31 CFR Chapter X, financial institutions must report certain transactions and maintain appropriate records.

31 USC 5324 — STRUCTURING TRANSACTIONS TO EVADE REPORTING REQUIREMENTS
(a) Domestic Currency Transactions. No person shall, for the purpose of evading the reporting requirements under Section 5313(a):
(1) cause or attempt to cause a domestic financial institution to fail to file a report;
(2) cause or attempt to cause a domestic financial institution to file a report that contains a material omission or misstatement; or
(3) structure or assist in structuring, or attempt to structure or assist in structuring, any transaction with one or more domestic financial institutions.

(b) International Currency Transactions. No person shall, for the purpose of evading the reporting requirements under Section 5316,:
(1) fail to file a report;
(2) file a report containing a material omission or misstatement; or
(3) structure or assist in structuring any importation or exportation of monetary instruments.

SECTION 2: PENALTIES FOR STRUCTURING
(a) Criminal Penalty: A person violating 31 USC 5324 is subject to a fine of not more than $250,000 or imprisonment for not more than 5 years, or both.

(b) Enhanced Penalty: If the violation is part of a pattern of illegal activity involving more than $100,000 in a 12-month period, the fine is not more than $500,000 and imprisonment is not more than 10 years.

SECTION 3: DEFINING STRUCTURING
Structuring (also called "smurfing") is the practice of conducting financial transactions in amounts below the reporting threshold to avoid triggering reporting requirements.

Key characteristics of structuring:
1. Breaking a large transaction into smaller transactions, each below the reporting threshold
2. Conducting multiple transactions at different branches or financial institutions
3. Using multiple accounts or multiple individuals to conduct the transactions
4. Transactions that are just below the reporting threshold (e.g., $9,500 when threshold is $10,000)
5. Transactions inconsistent with the customer's normal activity

SECTION 4: STRUCTURING INDICATORS FOR FINANCIAL INSTITUTIONS
Financial institutions should be alert to the following structuring indicators:

1. Cash deposits or withdrawals consistently just below $10,000
2. Multiple transactions in a single day at different branches
3. Transactions by multiple individuals on behalf of the same entity or person
4. Use of multiple accounts to deposit funds that total above the threshold
5. Customer inquiries about reporting thresholds
6. Deposits followed by immediate wire transfers to high-risk jurisdictions
7. Activity inconsistent with the stated business or occupation
8. Rapid movement of funds through multiple accounts

SECTION 5: OBLIGATIONS OF FINANCIAL INSTITUTIONS
1. File CTR for transactions exceeding $10,000 in currency
2. File SAR for suspected structuring, regardless of amount
3. Maintain transaction records for 5 years
4. Implement automated monitoring systems to detect structuring patterns
5. Train employees to recognize structuring indicators
6. Do not disclose to customers that a SAR has been filed (no tipping off)

SECTION 6: SAR FILING REQUIREMENTS
A SAR should be filed when:
1. The transaction is designed to evade BSA requirements (including structuring)
2. The transaction involves funds derived from illegal activity
3. The transaction has no lawful purpose or is unusual for the customer
4. The transaction involves the use of the financial institution to facilitate criminal activity

SAR Content Requirements:
1. Subject identification: Full name, address, SSN/TIN, account numbers
2. Transaction details: Amounts, dates, types of transactions
3. Suspicious activity description: Clear, chronological narrative
4. Connected accounts and related parties
5. Explanation of why the activity is suspicious

SECTION 7: COMMON STRUCTURING SCHEMES
Scheme 1: Multiple cash deposits just below $10,000 across different branches on the same day.

Scheme 2: Multiple individuals (smurfs) making deposits on behalf of the same business into different accounts.

Scheme 3: Structured deposits followed by wire transfers to offshore accounts.

Scheme 4: Use of money services businesses (MSBs) in conjunction with banks to avoid detection.

Scheme 5: Structured transactions layered through shell companies and nominee accounts.

SECTION 8: BEST PRACTICES FOR STRUCTURING DETECTION
1. Monitor for transactions at 80-100% of the reporting threshold
2. Aggregate related transactions by customer across all accounts
3. Cross-reference IP addresses, device fingerprints, and branch locations
4. Analyze time patterns to identify rapid succession transactions
5. Review transaction history for changes in normal patterns
6. Investigate transactions involving high-risk jurisdictions
7. Document all investigative steps and rationale for SAR filing

SECTION 9: CASE EXAMPLES
Example 1: A retail business deposits $9,500 daily for 10 consecutive days rather than one $95,000 deposit. This is a classic structuring pattern.

Example 2: Three individuals each deposit $9,800 into the same account at different branches within hours. This is a smurfing operation.

Example 3: A customer writes multiple checks to different individuals who then cash them at amounts below $10,000. This is check-based structuring.
"""

